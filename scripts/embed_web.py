# PlatformIO pre-build script: gzip the web UI into include/web_index.h so
# it is served straight from the firmware image.
#   web/index.html         -> WEB_INDEX_GZ, with the prompt texts of
#                             audio/prompts.json in place of /*PROMPTS*/{}
#   web/vendor/lame.min.js -> WEB_LAME_GZ, MP3 encoder for custom prompts
import gzip
import json
from pathlib import Path

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

root = Path(env["PROJECT_DIR"])  # noqa: F821
index = root / "web" / "index.html"
lame = root / "web" / "vendor" / "lame.min.js"
prompts = root / "audio" / "prompts.json"
dst = root / "include" / "web_index.h"
sources = [index, lame, prompts, root / "scripts" / "embed_web.py"]


def array(name, data):
    data = gzip.compress(data, 9, mtime=0)
    body = ",".join(str(b) for b in data)
    print(f"embed_web: {name} ({len(data)} bytes gz)")
    return (f"static const uint8_t {name}[] PROGMEM = {{{body}}};\n"
            f"static const size_t {name}_LEN = {len(data)};\n")


if not dst.exists() or max(s.stat().st_mtime for s in sources) > dst.stat().st_mtime:
    texts = json.loads(prompts.read_text())["prompts"]
    html = index.read_text()
    assert "/*PROMPTS*/{}" in html, "web/index.html: /*PROMPTS*/{} placeholder missing"
    html = html.replace("/*PROMPTS*/{}", json.dumps(texts, ensure_ascii=False, separators=(",", ":")))
    dst.write_text(
        "// Generated by scripts/embed_web.py from web/ - do not edit\n"
        "#pragma once\n#include <Arduino.h>\n"
        + array("WEB_INDEX_GZ", html.encode())
        + array("WEB_LAME_GZ", lame.read_bytes())
    )
